import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { artifacts } from "hardhat";

const CONTRACTS = ["LaoCarbonMarketplace", "LaoCarbonToken", "LaoCarbonCertificate", "MockUSDT"] as const;
const OUT = "web/src/lib/contracts.generated.ts";

async function main() {
  const abis: Record<string, unknown> = {};
  for (const name of CONTRACTS) abis[name] = (await artifacts.readArtifact(name)).abi;

  const addresses: Record<number, Record<string, string>> = {};
  const dir = "ignition/deployments";
  if (existsSync(dir)) {
    for (const entry of readdirSync(dir)) {
      const chainId = Number(entry.replace("chain-", ""));
      const file = `${dir}/${entry}/deployed_addresses.json`;
      if (!existsSync(file)) continue;
      const raw: Record<string, string> = JSON.parse(readFileSync(file, "utf8"));
      addresses[chainId] = Object.fromEntries(
        CONTRACTS.map((c) => [c, raw[`LaoCarbon#${c}`]]).filter(([, a]) => a),
      );
    }
  }

  const body = [
    "// Generated by scripts/export-web.ts — do not edit.",
    ...CONTRACTS.map((c) => `export const ${c}Abi = ${JSON.stringify(abis[c])} as const;`),
    `export const deployments: Record<number, Partial<Record<${CONTRACTS.map((c) => `"${c}"`).join(" | ")}, \`0x\${string}\`>>> = ${JSON.stringify(addresses, null, 2)};`,
    "",
  ].join("\n\n");
  writeFileSync(OUT, body);
  console.log(`Wrote ${OUT} (chains: ${Object.keys(addresses).join(", ") || "none"})`);
}

main().catch((e) => {
  console.error(e);
  process.exitCode = 1;
});
